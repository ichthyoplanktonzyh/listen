#!/usr/bin/env python3
"""Generate the local API TypeScript surface inventory from canonical OpenAPI."""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SPEC = ROOT / "contracts/openapi/v1.yaml"
DEFAULT_OUTPUT = ROOT / "contracts/generated/local-api-v1.ts"
VERSION = re.compile(r"^  version:\s*([0-9]+\.[0-9]+\.[0-9]+)\s*$", re.MULTILINE)
PATH = re.compile(r"^  (/v1/[^:\n]+):\s*$", re.MULTILINE)
OPERATION = re.compile(r"\boperationId:\s*([A-Za-z][A-Za-z0-9_]*)")
SCHEMA = re.compile(r"^    ([A-Za-z][A-Za-z0-9_]*):\s*$", re.MULTILINE)


class SurfaceError(ValueError):
    pass


def _schemas(document: str) -> list[str]:
    lines = document.splitlines()
    start = next(
        (index for index, line in enumerate(lines) if line == "  schemas:"), None
    )
    if start is None:
        raise SurfaceError("OpenAPI components.schemas section is missing")
    block: list[str] = []
    for line in lines[start + 1 :]:
        if line and not line.startswith("  "):
            break
        if line.startswith("  ") and not line.startswith("    "):
            break
        block.append(line)
    result = sorted(set(SCHEMA.findall("\n".join(block))))
    if not result:
        raise SurfaceError("OpenAPI components.schemas has no schemas")
    return result


def _component_block(document: str, name: str) -> list[str]:
    lines = document.splitlines()
    heading = next(
        (index for index, line in enumerate(lines) if line == f"    {name}:"), None
    )
    if heading is None:
        raise SurfaceError(f"OpenAPI component schema {name} is missing")
    end = heading + 1
    while end < len(lines) and not SCHEMA.fullmatch(lines[end]):
        end += 1
    return lines[heading:end]


def _enum_values(document: str, name: str) -> list[str]:
    match = re.search(r"\benum:\s*\[([^\]]+)\]", "\n".join(_component_block(document, name)))
    if match is None:
        raise SurfaceError(f"OpenAPI component schema {name} has no inline enum")
    values = [value.strip() for value in match.group(1).split(",")]
    if not values or any(not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*", value) for value in values):
        raise SurfaceError(f"OpenAPI component schema {name} has an unsupported enum")
    return values


def _literal_array(name: str, values: list[str]) -> str:
    entries = ",\n".join(f'    "{value}"' for value in values)
    return f"export const {name} = [\n{entries},\n] as const;\n"


def render(document: str) -> str:
    version_match = VERSION.search(document)
    if version_match is None:
        raise SurfaceError("OpenAPI info.version is missing")
    version = version_match.group(1)
    paths = sorted(set(PATH.findall(document)))
    operations = sorted(set(OPERATION.findall(document)))
    schemas = _schemas(document)
    material_capabilities = _enum_values(document, "MaterialCapability")
    if not paths or not operations:
        raise SurfaceError("OpenAPI has no /v1 paths or operationIds")

    parts = [
        "// Generated by core/scripts/generate_local_api_surface.py.\n",
        "// Canonical source: core/contracts/openapi/v1.yaml.\n",
        f'export const localApiV1ContractVersion = "{version}" as const;\n',
        _literal_array("localApiV1Paths", paths),
        _literal_array("localApiV1OperationIds", operations),
        _literal_array("localApiV1ComponentSchemas", schemas),
        "export type MaterialCapability = "
        + " | ".join(f'"{value}"' for value in material_capabilities)
        + ";\n",
        "export type LocalApiV1Path = (typeof localApiV1Paths)[number];\n",
        "export type LocalApiV1OperationId = (typeof localApiV1OperationIds)[number];\n",
        "export type LocalApiV1ComponentSchema = (typeof localApiV1ComponentSchemas)[number];\n",
        """
// Package lifecycle signatures are kept explicit because Core's lifecycle
// integration tests use this generated surface as a consumer contract.
export interface InstallMaterialPackageRequest {
  package_path: string;
}

export interface AdoptLearningEditionRequest {
  release_id: string;
}

export interface LearningEditionResource {
  resource_id: string;
  kind: string;
  role: "base" | "assistance";
  required: boolean;
  availability: "available" | "missing" | "opaque";
  review_status: "unreviewed" | "machine_checked" | "human_reviewed";
  content_language: string | null;
  support_languages: string[];
}

export interface LearningEditionRendition {
  rendition_id: string;
  kind: string;
  available: boolean;
}

export interface LearningEditionDetails {
  material_id: string;
  material_revision_id: string;
  edition_id: string;
  release_id: string;
  title: string;
  target_language: string;
  support_languages: string[];
  available_capabilities: MaterialCapability[];
  installed_at_ms: number;
  adopted_at_ms: number | null;
  adopted: boolean;
  resources: LearningEditionResource[];
  renditions: LearningEditionRendition[];
}

export interface LocalPackageLifecycleApi {
  installMaterialPackage(
    materialId: string,
    input: InstallMaterialPackageRequest,
  ): Promise<LearningEditionDetails>;
  listLearningEditions(materialId: string): Promise<LearningEditionDetails[]>;
  deleteLearningEdition(materialId: string, releaseId: string): Promise<void>;
  adoptLearningEdition(
    materialId: string,
    input: AdoptLearningEditionRequest,
  ): Promise<LearningEditionDetails>;
}
""",
    ]
    return "\n".join(part.strip("\n") for part in parts) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--spec", type=Path, default=DEFAULT_SPEC)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="write the generated snapshot")
    mode.add_argument("--check", action="store_true", help="fail when the snapshot is stale")
    args = parser.parse_args(argv)

    try:
        expected = render(args.spec.read_text(encoding="utf-8"))
    except (OSError, SurfaceError) as error:
        print(f"local API surface generation failed: {error}", file=sys.stderr)
        return 1

    if args.write:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(expected, encoding="utf-8")
        print(f"Generated {args.output}")
        return 0

    try:
        actual = args.output.read_text(encoding="utf-8")
    except OSError as error:
        print(f"local API surface snapshot is missing: {error}", file=sys.stderr)
        return 1
    if actual != expected:
        print(
            "local API surface snapshot is stale; run "
            "python3 scripts/generate_local_api_surface.py --write",
            file=sys.stderr,
        )
        return 1
    print("Generated local API TypeScript surface matches OpenAPI.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
